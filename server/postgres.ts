export function isPostgresConfigured(): boolean {
  return Boolean(globalThis.__rxorbitPgPool || process.env.DATABASE_URL?.trim());
}

function parsePositiveInt(raw: string | undefined, fallback: number): number {
  if (!raw) return fallback;
  const parsed = Number.parseInt(raw, 10);
  return Number.isFinite(parsed) && parsed > 0 ? parsed : fallback;
}

function isLocalDatabaseHost(connectionString: string): boolean {
  try {
    const parsed = new URL(connectionString);
    const host = parsed.hostname.toLowerCase();
    return host === 'localhost' || host === '127.0.0.1' || host === '::1';
  } catch {
    return false;
  }
}

export function buildPoolConfig(connectionString: string): PoolConfig {
  const sslSetting = (process.env.DATABASE_SSL ?? process.env.PGSSLMODE ?? '').trim().toLowerCase();
  const rejectUnauthorized =
    (process.env.DATABASE_SSL_REJECT_UNAUTHORIZED ?? '').trim().toLowerCase() === 'true';

  let ssl: PoolConfig['ssl'];
  if (sslSetting === 'disable' || sslSetting === 'false' || sslSetting === 'off') {
    ssl = false;
  } else if (
    sslSetting === 'require' ||
    sslSetting === 'true' ||
    sslSetting === 'verify-ca' ||
    sslSetting === 'verify-full' ||
    !isLocalDatabaseHost(connectionString)
  ) {
    ssl = {
      rejectUnauthorized:
        rejectUnauthorized || sslSetting === 'verify-ca' || sslSetting === 'verify-full',
    };
  }

  return {
    connectionString,
    max: parsePositiveInt(process.env.PG_POOL_MAX, 10),
    idleTimeoutMillis: parsePositiveInt(process.env.PG_IDLE_TIMEOUT_MS, 30_000),
    connectionTimeoutMillis: parsePositiveInt(process.env.PG_CONNECTION_TIMEOUT_MS, 15_000),
    application_name: 'rxorbit-backend',
    ssl,
  };
}

export function getPostgresPool(): Pool {
  if (globalThis.__rxorbitPgPool) {
    return globalThis.__rxorbitPgPool;
  }

  const connectionString = process.env.DATABASE_URL?.trim();
  if (!connectionString) {
    const err: PostgresServiceError = new Error(
      'PostgreSQL connection is not configured. Set DATABASE_URL in the server environment.'
    );
    err.statusCode = 500;
    throw err;
  }

  const pool = new Pool(buildPoolConfig(connectionString));
  pool.on('error', (poolError) => {
    console.error('[postgres] Unexpected idle client error:', poolError.message);
  });

  globalThis.__rxorbitPgPool = pool;
  return pool;
}

export async function closePostgresPool(): Promise<void> {
  if (globalThis.__rxorbitPgPool) {
    const pool = globalThis.__rxorbitPgPool;
    globalThis.__rxorbitPgPool = undefined;
    await pool.end();
  }
}

export function sanitizePostgresError(err: unknown): PostgresServiceError {
  const pgErr = err as { code?: string; message?: string; statusCode?: number };
  const code = typeof pgErr?.code === 'string' ? pgErr.code : undefined;

  let message = 'Database operation failed.';
  let statusCode = typeof pgErr?.statusCode === 'number' ? pgErr.statusCode : 500;

  if (code === '23505') {
    message = 'A record with this unique value already exists.';
    statusCode = 409;
  } else if (code === '23503') {
    message = 'Referenced record does not exist or cannot be removed while referenced.';
    statusCode = 400;
  } else if (code === '23502' || code === '22P02' || code === '23514') {
    message = 'Invalid database field value.';
    statusCode = 400;
  } else if (code === '57P01' || code === '57P02' || code === '57P03' || code === 'ECONNREFUSED') {
    message = 'Database service is temporarily unavailable.';
    statusCode = 503;
  } else if (!code && pgErr?.message && !pgErr.message.includes('postgres://') && !pgErr.message.includes('postgresql://')) {
    message = pgErr.message;
  }

  const wrapped: PostgresServiceError = new Error(message, { cause: err });
  wrapped.code = code;
  wrapped.statusCode = statusCode;
  return wrapped;
}

export async function pgQuery<T extends QueryResultRow = QueryResultRow>(
  text: string,
  params: readonly SqlParam[] = [],
  client?: PoolClient
): Promise<QueryResult<T>> {
  const executor = client ?? getPostgresPool();
  try {
    return await executor.query<T>(text, [...params]);
  } catch (err) {
    throw sanitizePostgresError(err);
  }
}

export async function pgQueryRows<T extends QueryResultRow = QueryResultRow>(
  text: string,
  params: readonly SqlParam[] = [],
  client?: PoolClient
): Promise<T[]> {
  const result = await pgQuery<T>(text, params, client);
  return result.rows;
}

export async function pgQueryOne<T extends QueryResultRow = QueryResultRow>(
  text: string,
  params: readonly SqlParam[] = [],
  client?: PoolClient
): Promise<T | null> {
  const result = await pgQuery<T>(text, params, client);
  return result.rows[0] ?? null;
}

export async function pgExecute(
  text: string,
  params: readonly SqlParam[] = [],
  client?: PoolClient
): Promise<{ rowCount: number }> {
  const result = await pgQuery(text, params, client);
  return { rowCount: result.rowCount ?? 0 };
}

export async function pgWithTransaction<T>(fn: (client: PoolClient) => Promise<T>): Promise<T> {
  const pool = getPostgresPool();
  let client: PoolClient;
  try {
    client = await pool.connect();
  } catch (err) {
    throw sanitizePostgresError(err);
  }

  try {
    await client.query('BEGIN');
    const result = await fn(client);
    await client.query('COMMIT');
    return result;
  } catch (err) {
    try {
      await client.query('ROLLBACK');
    } catch (rollbackErr) {
      console.error('[postgres] Rollback failed:', (rollbackErr as Error)?.message ?? 'Unknown error');
    }
    throw sanitizePostgresError(err);
  } finally {
    client.release();
  }
}

export async function pgHealthCheck(): Promise<{ ok: boolean; latencyMs: number }> {
  const startedAt = Date.now();
  await pgQuery('SELECT 1 AS ok');
  return {
    ok: true,
    latencyMs: Date.now() - startedAt,
  };
}

export function toIsoTimestamp(value: Date | string | null | undefined): string {
  if (!value) return '';
  if (value instanceof Date) return value.toISOString();
  const parsed = Date.parse(value);
  return Number.isNaN(parsed) ? String(value) : new Date(parsed).toISOString();
}

export function toPgBoolean(value: unknown): boolean {
  if (typeof value === 'boolean') return value;
  if (typeof value === 'number') return value !== 0;
  if (typeof value === 'string') {
    const normalized = value.trim().toLowerCase();
    return normalized === 'true' || normalized === '1' || normalized === 't' || normalized === 'yes';
  }
  return Boolean(value);
}

export function toPgInt(value: unknown, fallback = 0): number {
  if (typeof value === 'number') return Number.isFinite(value) ? Math.trunc(value) : fallback;
  if (typeof value === 'bigint') return Number(value);
  if (typeof value === 'string' && value.trim()) {
    const parsed = Number.parseInt(value, 10);
    return Number.isFinite(parsed) ? parsed : fallback;
  }
  return fallback;
}

export async function initializePostgresDatabase(): Promise<void> {
  await pgWithTransaction(async (client) => {
    for (const statement of POSTGRES_SCHEMA_STATEMENTS) {
      await client.query(statement);
    }
  });
}

export async function syncPostgresIdentitySequences(client?: PoolClient): Promise<void> {
  const run = async (txClient: PoolClient) => {
    for (const table of IDENTITY_TABLES) {
      await txClient.query(
        `SELECT setval(
           pg_get_serial_sequence($1, 'id'),
           COALESCE((SELECT MAX(id) FROM ${table}), 1),
           (SELECT COUNT(*) > 0 FROM ${table})
         );`,
        [table]
      );
    }
  };

  if (client) {
    await run(client);
  } else {
    await pgWithTransaction(run);
  }
}
